#include "ft_printf.h"

int	ft_isvalid(char c)
{
	return (
		c == 'c'
		|| c == 's'
		|| c == 'p'
		|| c == 'd'
		|| c == 'i'
		|| c == 'u'
		|| c == 'x'
		|| c == 'X'
		|| c == '%'
	);
}
